def build_parser() -> argparse.ArgumentParser:
    """
    Build the argument parser for the YCSB entry script.

    Extracted from ``if __name__ == '__main__':`` so it can be imported and
    fed a synthetic argv (e.g. ``build_parser().parse_args(argv)``) by
    ``experiment.py`` for a catalog-driven ``experiment.yml`` whose argv is
    generated by :func:`bexhoma.spec.build_argv`, instead of re-declaring
    these flags by hand. Mirrors :func:`tpch.build_parser`.

    :return: Configured argument parser.
    :rtype: argparse.ArgumentParser
    """
    description = """Run YCSB key-value benchmarks against a DBMS in Kubernetes.
    SF controls dataset size: SF million rows and (by default) SF million operations.
    Supports throughput targets, connection pooling, and multiple workload types.
    """
    parser = argparse.ArgumentParser(description=description, parents=[make_base_parser()])
    parser.add_argument('mode', help='experiment phase: load data, run the benchmark, start SUT only, or summarize results', choices=['run', 'start', 'load', 'summary'], default='run')
    parser.add_argument('-dbms', '--dbms', help='one or more DBMS engines to test', choices=dbms_choices('ycsb'), default=[], nargs='*')
    parser.add_argument('-xnlf',  '--xnum-loading-target-factors', help='comma-separated multipliers for the loading ops target (target = -xtb × factor)', default="1", dest='num_loading_target_factors')
    parser.add_argument('-xnsr',  '--xnum-sut-replicas', help='number of SUT replicas per configuration', default=1, dest='num_sut_replicas')
    parser.add_argument('-xnpd',  '--xnum-pd-nodes', help='number of PD (Placement Driver) nodes, independent of -nw (TiDB only; keep odd)', default=3, dest='num_pd_nodes')
    parser.add_argument('-xnbf',  '--xnum-benchmarking-target-factors', help='comma-separated multipliers for the benchmarking ops target (target = -xtb × factor)', default="1", dest='num_benchmarking_target_factors')
    parser.add_argument('-xnpp',  '--xnum-pooling-pods', help='comma-separated list of connection-pooler pod counts', default="1", dest='num_pooling_pods')
    parser.add_argument('-xnpi',  '--xnum-pooling-in', help='comma-separated list of max inbound connections per pooler pod', default="", dest='num_pooling_in')
    parser.add_argument('-xnpo',  '--xnum-pooling-out', help='comma-separated list of max outbound connections per pooler pod (to the DBMS)', default="", dest='num_pooling_out')
    parser.add_argument('-xwl',   '--xworkload', help='YCSB workload letter (a=read-heavy, a2=read-heavy with uniform instead of zipfian request distribution, b=read-mostly, c=read-only, c2=read-only with uniform instead of zipfian request distribution, d=read-latest, e=scan, f=read-modify-write)', choices=['a', 'a2', 'b', 'c', 'c2', 'd', 'e', 'f'], default='', dest='workload')
    parser.add_argument('-xop',   '--xnum-operations', help='total operation count in millions (overrides SF for operations; default: use SF)', default=None, dest='scaling_factor_operations')
    parser.add_argument('-xsbs',  '--xscaling-batchsize', help='batch size for insert operations', default="", dest='scaling_batchsize')
    parser.add_argument('-xli',   '--xlogging-interval', help='status logging interval in seconds', default=10, dest='scaling_logging')
    parser.add_argument('-xio',   '--extra-insert-order', help='key insertion order: hashed (uniform) or ordered (sequential)', default='hashed', choices=['hashed', 'ordered'])
    parser.add_argument('-xtb',   '--xtarget-base', help='base ops-per-second target; multiply by -xnlf/-xnbf factors to get per-pod target', default="16384", dest='target_base')
    parser.add_argument('-xmet',  '--xmax-execution-time', help='maximum execution time in seconds for loading and benchmarking (0 = no limit)', default=0, type=int, dest='max_execution_time')
    return parser


def run(args: argparse.Namespace, on_experiment_built=None) -> None:
    """
    Build and run a YCSB experiment from an already-parsed argparse Namespace.

    Pure extraction of ``ycsb.py``'s own dispatch/build logic (everything that
    used to live directly under ``if __name__ == '__main__':``), so it can be
    invoked in-process -- e.g. by ``experiment.py`` for a catalog-driven
    ``experiment.yml`` whose argv is generated by
    :func:`bexhoma.spec.build_argv` -- without spawning a subprocess or
    re-parsing anything through this module's own CLI a second time. Mirrors
    :func:`tpch.run`.

    :param args: Parsed CLI arguments, as returned by ``build_parser().parse_args(...)``.
    :param on_experiment_built: Optional callback, invoked with the built
        experiment right after its result folder is created but before
        ``prepare_testbed()``/``process()`` run. Never called for a plain
        ``python ycsb.py ...`` invocation.
    """
    if args.debug:
        logging.basicConfig(level=logging.DEBUG)
    if args.debug:
        logger_bexhoma = logging.getLogger('bexhoma')
        logger_bexhoma.setLevel(logging.DEBUG)
        logger_loader = logging.getLogger('load_data_asynch')
        logger_loader.setLevel(logging.DEBUG)
    ##############
    ### set parameters
    ##############
    command_args = vars(args)
    ##############
    ### workflow parameters
    ##############
    # start with old experiment?
    code = args.experiment
    # only create testbed or also run a benchmark?
    mode = str(args.mode)
    # scaling of data
    SF = str(args.scaling_factor)
    # timeout of a benchmark
    timeout = int(args.timeout)
    # how often to repeat experiment?
    num_experiment_to_apply = int(args.num_config)
    # configure number of clients per config
    list_clients = args.num_query_executors.split(",")
    if len(list_clients) > 0:
        list_clients = [int(x) for x in list_clients if len(x) > 0]
    else:
        list_clients = []
    ##############
    ### specific to: YCSB
    ##############
    SFO = str(args.scaling_factor_operations)
    if SFO == 'None':
        SFO = SF
    ycsb_rows = int(SF)*1000000 # 1kb each, that is SF is size in GB
    ycsb_operations = int(SFO)*1000000
    target_base = int(args.target_base)
    batchsize = args.scaling_batchsize
    scaling_logging = int(args.scaling_logging) # ycsb expects seconds? *1000 # adjust unit to miliseconds
    extra_insert_order = args.extra_insert_order                 # insert keys by ordering or by hashed value
    workload = args.workload
    max_execution_time = int(args.max_execution_time)
    ##############
    ### set cluster
    ##############
    aws = args.aws
    if aws:
        cluster = clusters.AWS(context=args.context)
        # scale up
        node_sizes = {
            'auxiliary': 1,
            'sut-mid': 1,
            'benchmarker': 1
        }
        #cluster.scale_nodegroups(node_sizes)
    else:
        cluster = clusters.Kubernetes(context=args.context)
    cluster_name = cluster.contextdata['clustername']
    if args.max_sut is not None:
        cluster.max_sut = int(args.max_sut)
    # set experiment
    if code is None:
        code = cluster.code
    # summary mode resumes an existing experiment: use its own persisted SF
    # instead of the -sf CLI default (see resolve_scaling_factor docstring)
    SF = resolve_scaling_factor(cluster, code, mode, args.scaling_factor)
    ##############
    ### prepare and configure experiment
    ##############
    experiment = experiments.YcsbExperiment(cluster=cluster, SF=SF, timeout=timeout, code=code, num_experiment_to_apply=num_experiment_to_apply)
    if on_experiment_built is not None:
        on_experiment_built(experiment)
    if args.max_sut_experiment is not None:
        experiment.max_sut = int(args.max_sut_experiment)
    experiment.prometheus_interval = "30s"
    experiment.prometheus_timeout = "30s"
    # remove running dbms
    #experiment.clean()
    experiment.prepare_testbed(command_args)
    # the key order of the loaded data: stored on volumes (load_insert_order), compared on reuse
    experiment.data_parameters['insert_order'] = args.extra_insert_order
    num_loading_pods = experiment.get_parameter_as_list('num_loading_pods')
    num_loading_threads = experiment.get_parameter_as_list('num_loading_threads')
    num_loading_target_factors = experiment.get_parameter_as_list('num_loading_target_factors')
    num_benchmarking_pods = experiment.get_parameter_as_list('num_benchmarking_pods')
    num_benchmarking_threads = experiment.get_parameter_as_list('num_benchmarking_threads')
    num_benchmarking_target_factors = experiment.get_parameter_as_list('num_benchmarking_target_factors')
    num_pooling_pods = experiment.get_parameter_as_list('num_pooling_pods')
    num_pooling_in = experiment.get_parameter_as_list('num_pooling_in')
    num_pooling_out = experiment.get_parameter_as_list('num_pooling_out')
    # if we want to loop over pooling pods, we only allow 1 configuration of loading pods (number and target)
    # this is because naming length is limited in k8s
    # deactivated: truncating the loading sweep silently drops requested configurations
    #if len(num_pooling_pods) > 1:
    #    num_loading_pods = [num_loading_pods[0]]
    #    num_loading_threads = [num_loading_threads[0]]
    # set node labes for components
    if aws:
        # set node labes for components
        experiment.set_nodes(
            sut = 'sut',
            loading = 'sut',
            monitoring = 'auxiliary',
            benchmarking = 'auxiliary',
            )
    # add labels about the use case
    experiment.set_additional_labels(
        usecase="ycsb",
        experiment_design="compare-scaleout",
        rows=ycsb_rows,
        operations=ycsb_operations,
        workload=workload,
        )
    experiment.set_default_loading_parameters(
        SF = SF,
        BEXHOMA_SYNCH_LOAD = 1,
        YCSB_STATUS = 1,
        YCSB_WORKLOAD = workload,
        YCSB_ROWS = ycsb_rows,
        YCSB_BATCHSIZE = batchsize,
        YCSB_STATUS_INTERVAL = scaling_logging,
        YCSB_INSERTORDER = extra_insert_order,
        YCSB_MAX_EXECUTION = 0, #max_execution_time, # we always load the full dataset
    )
    experiment.set_default_benchmarking_parameters(
        SF = SF,
        BEXHOMA_SYNCH_LOAD = 1,
        YCSB_STATUS = 1,
        YCSB_WORKLOAD = workload,
        YCSB_ROWS = ycsb_rows,
        YCSB_BATCHSIZE = batchsize,
        YCSB_STATUS_INTERVAL = scaling_logging,
        YCSB_INSERTORDER = extra_insert_order,
        YCSB_MAX_EXECUTION = max_execution_time,
    )
    ##############
    ### add configs of dbms to be tested
    ##############
    for loading_threads in num_loading_threads:
        for loading_pods in num_loading_pods:
            for factor_loading in num_loading_target_factors:
                loading_target = target_base*factor_loading
                loading_threads_per_pod = int(loading_threads/loading_pods)
                ycsb_operations_per_pod = int(ycsb_operations/loading_pods)
                loading_target_per_pod = int(loading_target/loading_pods)
                # every DBMS that can run YCSB (or the ones named by -dbms), as declared in cluster.config
                for docker in selected_dockers(cluster.dockers, 'ycsb', args.dbms, args):
                    # the entry of the DBMS, with the variants the command line selects (e.g. a cluster with -nw)
                    entry = entry_of(cluster.dockers, docker, 'ycsb', args)
                    # a DBMS behind a connection pooler gets a configuration per pooler setting
                    for pooling in pooling_variants(entry, num_pooling_pods,
                                                    num_pooling_in or [int(loading_threads)],
                                                    num_pooling_out or [int(loading_threads)]):
                        config = build_configuration(
                            experiment, docker, 'ycsb', args,
                            loading_parameters={
                                'PARALLEL': str(loading_pods),
                                'YCSB_THREADCOUNT': loading_threads_per_pod,
                                'YCSB_TARGET': loading_target_per_pod,
                                'YCSB_OPERATIONS': ycsb_operations_per_pod,
                            },
                            pooling=pooling or None)
                        # A catalog-driven run (experiment.py) sets apply_sut_resources
                        # when the experiment.yml carries a resources: block; a plain
                        # `python ycsb.py` invocation leaves it unset and the SUT pod
                        # keeps running without resource requests/limits, as before.
                        if getattr(args, 'apply_sut_resources', False):
                            config.set_resources(
                                requests = {'cpu': args.request_cpu, 'memory': args.request_ram, 'gpu': 0},
                                limits = {'cpu': args.limit_cpu, 'memory': args.limit_ram},
                                )
                        config.set_loading(parallel=loading_pods, num_pods=loading_pods)
                        benchmarking_parameters = entry_parameters(
                            cluster.dockers, docker, 'ycsb', 'benchmarking_parameters', args)
                        executor_list = []
                        for factor_benchmarking in num_benchmarking_target_factors:
                            benchmarking_target = target_base*factor_benchmarking
                            for benchmarking_threads in num_benchmarking_threads:
                                for benchmarking_pods in num_benchmarking_pods:
                                    for num_executor in list_clients:
                                        benchmarking_pods_scaled = num_executor*benchmarking_pods
                                        benchmarking_threads_per_pod = int(benchmarking_threads/benchmarking_pods)
                                        ycsb_operations_per_pod = int(ycsb_operations/benchmarking_pods_scaled)
                                        benchmarking_target_per_pod = int(benchmarking_target/benchmarking_pods)
                                        executor_list.append(benchmarking_pods_scaled)
                                        config.add_benchmarking_parameters(
                                            **benchmarking_parameters,
                                            PARALLEL = str(benchmarking_pods_scaled),
                                            YCSB_THREADCOUNT = benchmarking_threads_per_pod,
                                            YCSB_TARGET = benchmarking_target_per_pod,
                                            YCSB_OPERATIONS = ycsb_operations_per_pod,
                                            )
                        config.add_benchmark_list(executor_list)
    ##############
    ### wait for necessary nodegroups to have planned size
    ##############
    if aws:
        #cluster.wait_for_nodegroups(node_sizes)
        pass
    ##############
    ### branch for workflows
    ##############
    experiment.process()


if __name__ == '__main__':
    parser = build_parser()
    args = parser.parse_args()
    reason = tenancy_error('ycsb', args)
    if reason:
        parser.error(reason)
    run(args)
    exit()
